-- 平台核心表（S0）
-- 版本号约定：life-core 用 V1_x，出游 V2_x，日程 V3_x，健身 V4_x，记账 V5_x，内容总结 V6_x，管理后台 V9_x
-- 所有业务表带 user_id；共享数据带 space_id；tenant_id 预留（默认 0，暂不过滤）
-- Graph 断点表由 Spring AI Alibaba 的 PostgresSaver 自己创建，不在这里维护

-- ========== 账号 ==========
CREATE TABLE t_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT       NOT NULL DEFAULT 0,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    nickname      VARCHAR(64),
    phone_enc     TEXT,                                  -- 预留：手机号加密存储
    timezone      VARCHAR(40)  NOT NULL DEFAULT 'Asia/Shanghai',
    status        SMALLINT     NOT NULL DEFAULT 1,       -- 1 正常 0 禁用
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 共享空间（家庭、旅行团），表先建，S2 启用
CREATE TABLE t_space (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL DEFAULT 0,
    name       VARCHAR(64) NOT NULL,
    owner_id   BIGINT      NOT NULL REFERENCES t_user (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE t_space_member (
    space_id  BIGINT      NOT NULL REFERENCES t_space (id),
    user_id   BIGINT      NOT NULL REFERENCES t_user (id),
    role      VARCHAR(16) NOT NULL,                      -- OWNER / EDITOR / VIEWER
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (space_id, user_id)
);

-- 个人访问令牌：iOS 快捷指令、ICS 日历订阅等没法走登录的场景；S3 也用于第三方开放 API
CREATE TABLE t_api_key (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES t_user (id),
    name         VARCHAR(64)  NOT NULL,
    scope        VARCHAR(32)  NOT NULL,                  -- 单一用途：CALENDAR_FEED / HEALTH_SYNC ...
    key_prefix   VARCHAR(12)  NOT NULL,                  -- 明文前几位，方便用户辨认
    key_hash     VARCHAR(64)  NOT NULL UNIQUE,           -- SHA-256，只存哈希
    last_used_at TIMESTAMPTZ,
    revoked_at   TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_api_key_user ON t_api_key (user_id);

-- ========== 会话 ==========
CREATE TABLE t_conversation (
    id         VARCHAR(64)  PRIMARY KEY,                 -- 同时作为 Graph 的 threadId
    user_id    BIGINT       NOT NULL REFERENCES t_user (id),
    space_id   BIGINT       NOT NULL DEFAULT 0,
    title      VARCHAR(128),
    skill_id   VARCHAR(32),                              -- 最近一次路由到的技能
    status     VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',   -- ACTIVE / WAITING_USER / ARCHIVED
    summary    TEXT,                                     -- 长对话压缩后的摘要
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_conversation_user ON t_conversation (user_id, updated_at DESC);

CREATE TABLE t_chat_message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id VARCHAR(64) NOT NULL REFERENCES t_conversation (id) ON DELETE CASCADE,
    role            VARCHAR(16) NOT NULL,                -- USER / ASSISTANT / SYSTEM / TOOL
    content         TEXT        NOT NULL,
    metadata        JSONB,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_chat_message_conv ON t_chat_message (conversation_id, id);

-- ========== 记忆 ==========
CREATE TABLE t_memory (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES t_user (id),
    space_id    BIGINT        NOT NULL DEFAULT 0,
    category    VARCHAR(32)   NOT NULL,                  -- PROFILE / PREFERENCE / HEALTH / RELATION / FINANCE
    mem_key     VARCHAR(64)   NOT NULL,
    content     TEXT          NOT NULL,                  -- sensitive=true 时为密文
    source      VARCHAR(16)   NOT NULL,                  -- USER_STATED / AI_INFERRED / IMPORTED
    confidence  NUMERIC(3, 2) NOT NULL DEFAULT 1.00,
    sensitive   BOOLEAN       NOT NULL DEFAULT FALSE,    -- 敏感记忆加密存储，默认不进 Prompt
    expire_at   TIMESTAMPTZ,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (user_id, category, mem_key)
);

-- ========== 日程与通知 ==========
CREATE TABLE t_schedule_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES t_user (id),
    space_id    BIGINT       NOT NULL DEFAULT 0,
    title       VARCHAR(128) NOT NULL,
    description TEXT,
    location    VARCHAR(256),
    start_at    TIMESTAMPTZ  NOT NULL,
    end_at      TIMESTAMPTZ,
    all_day     BOOLEAN      NOT NULL DEFAULT FALSE,
    source      VARCHAR(32)  NOT NULL DEFAULT 'USER',   -- USER / TRAVEL / FITNESS ...
    source_ref  VARCHAR(64),                             -- 来源对象 id，如行程 id
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_schedule_event_user_time ON t_schedule_event (user_id, start_at);

CREATE TABLE t_reminder (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES t_user (id),
    event_id   BIGINT       REFERENCES t_schedule_event (id) ON DELETE CASCADE,
    title      VARCHAR(128) NOT NULL,
    body       TEXT,
    url        VARCHAR(512),                             -- 点击通知打开的页面
    level      VARCHAR(16)  NOT NULL DEFAULT 'active',   -- Bark：active / timeSensitive / passive / critical
    remind_at  TIMESTAMPTZ  NOT NULL,
    status     VARCHAR(16)  NOT NULL DEFAULT 'PENDING',  -- PENDING / SENT / FAILED / CANCELLED
    attempts   INT          NOT NULL DEFAULT 0,
    last_error TEXT,
    sent_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- 服务重启后补发：调度器按 remind_at <= now() AND status = 'PENDING' 捞取
CREATE INDEX idx_reminder_due ON t_reminder (status, remind_at);

CREATE TABLE t_notify_channel (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES t_user (id),
    type        VARCHAR(16) NOT NULL,                    -- BARK（以后：NTFY / MINIAPP / WEBPUSH）
    config_enc  TEXT        NOT NULL,                    -- 加密后的 JSON：Bark 设备 key、加密密钥等
    enabled     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, type)
);

CREATE TABLE t_notification (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES t_user (id),
    channel     VARCHAR(16)  NOT NULL,
    title       VARCHAR(128) NOT NULL,
    reminder_id BIGINT,
    success     BOOLEAN      NOT NULL,
    error       TEXT,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_notification_user ON t_notification (user_id, created_at DESC);

-- ========== 审计与用量 ==========
CREATE TABLE t_tool_call_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT,
    conversation_id VARCHAR(64),
    skill_id        VARCHAR(32),
    tool_name       VARCHAR(64) NOT NULL,
    input           JSONB,
    output_digest   TEXT,
    latency_ms      INT,
    success         BOOLEAN     NOT NULL,
    error           TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_tool_call_conv ON t_tool_call_log (conversation_id, created_at);

CREATE TABLE t_llm_usage (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT,
    conversation_id   VARCHAR(64),
    purpose           VARCHAR(32) NOT NULL,              -- ROUTER / SKILL / SUMMARY / EVAL ...
    model             VARCHAR(64) NOT NULL,
    prompt_tokens     INT         NOT NULL DEFAULT 0,
    completion_tokens INT         NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_llm_usage_day ON t_llm_usage (created_at);

-- ========== 管理端 ==========
CREATE TABLE t_admin_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    status        SMALLINT     NOT NULL DEFAULT 1,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE t_admin_op_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id   BIGINT       NOT NULL,
    action     VARCHAR(64)  NOT NULL,
    target     VARCHAR(128),
    detail     JSONB,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE t_eval_run (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_by  VARCHAR(32)  NOT NULL,                   -- ADMIN / CI
    total       INT          NOT NULL DEFAULT 0,
    passed      INT          NOT NULL DEFAULT 0,
    result      JSONB,
    started_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ
);

-- ========== ShedLock（定时任务防重） ==========
CREATE TABLE shedlock (
    name       VARCHAR(64)  NOT NULL PRIMARY KEY,
    lock_until TIMESTAMP    NOT NULL,
    locked_at  TIMESTAMP    NOT NULL,
    locked_by  VARCHAR(255) NOT NULL
);
