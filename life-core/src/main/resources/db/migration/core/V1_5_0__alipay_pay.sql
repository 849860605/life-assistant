-- 支付宝收款（AI 网页应用收款，alipay.trade.page.pay）：商户订单、退款请求、异步通知幂等记录
-- 金额一律 NUMERIC(12,2)，单位元；状态以支付宝异步通知（已验签）或主动查询结果为准，同步回跳不改状态

-- 商户订单：下单前先落库，out_trade_no 商户侧唯一；app_id 记下单时用的应用（沙箱或正式），通知校验时比对
CREATE TABLE t_pay_order (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL REFERENCES t_user (id),
    out_trade_no VARCHAR(64)   NOT NULL UNIQUE,
    app_id       VARCHAR(32)   NOT NULL,
    subject      VARCHAR(256)  NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL,
    status       VARCHAR(16)   NOT NULL DEFAULT 'WAIT_PAY', -- WAIT_PAY 待支付 / PAID 已支付 / CLOSED 已关闭
    trade_no     VARCHAR(64),                              -- 支付宝交易号，支付成功后才有
    paid_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_pay_order_user ON t_pay_order (user_id, created_at DESC);

-- 退款请求：每次新退款一个新的 out_request_no；结果未知时用同一个编号和同样的金额重试，防止重复退款
CREATE TABLE t_pay_refund (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    out_trade_no   VARCHAR(64)    NOT NULL REFERENCES t_pay_order (out_trade_no),
    out_request_no VARCHAR(64)    NOT NULL UNIQUE,
    refund_amount  NUMERIC(12, 2) NOT NULL,
    reason         VARCHAR(256),
    status         VARCHAR(16)    NOT NULL DEFAULT 'PENDING', -- PENDING 结果待确认 / SUCCESS 退款成功 / FAILED 支付宝明确拒绝
    message        VARCHAR(256),                               -- 最近一次支付宝返回的说明（失败原因等）
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX idx_pay_refund_order ON t_pay_refund (out_trade_no);

-- 异步通知幂等：同一 notify_id 只处理一次；params 存去掉签名后的原始参数，方便对账排查
CREATE TABLE t_pay_notify_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notify_id    VARCHAR(128) NOT NULL UNIQUE,
    out_trade_no VARCHAR(64)  NOT NULL,
    trade_no     VARCHAR(64),
    trade_status VARCHAR(32),
    params       JSONB        NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_pay_notify_order ON t_pay_notify_event (out_trade_no);
