-- 积分：按用多少扣多少收费（替代月度会员）。1 元 = 100 积分。
-- balance 是买的和送的（注册赠送、后台调整）积分，可以小于 0（AI 已经干完活才扣、余额不够时先透支，下次补）；
-- 每天赠送的积分单独记（daily_date 当天还剩 daily_left），当天用不完不累积，扣费时先扣它。
CREATE TABLE t_credit_account
(
    user_id    BIGINT PRIMARY KEY REFERENCES t_user (id) ON DELETE CASCADE,
    balance    BIGINT      NOT NULL DEFAULT 0,
    daily_date DATE,
    daily_left INT         NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 积分流水：kind 为 SIGNUP 注册赠送 / PURCHASE 购买 / SPEND 使用 / RETURN 失败退回 / ADMIN 后台调整 / REFUND 订单退款扣回；
-- amount 正数加、负数扣（扣的时候是总数，其中 from_daily 是每日赠送抵掉的部分）；ref 是订单号、会话 id、航班号等
CREATE TABLE t_credit_ledger
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES t_user (id) ON DELETE CASCADE,
    kind          VARCHAR(16)  NOT NULL,
    feature       VARCHAR(32),
    amount        INT          NOT NULL,
    from_daily    INT          NOT NULL DEFAULT 0,
    balance_after BIGINT       NOT NULL,
    ref           VARCHAR(80),
    note          VARCHAR(200),
    admin_id      BIGINT,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_credit_ledger_user ON t_credit_ledger (user_id, id DESC);
CREATE INDEX idx_credit_ledger_time ON t_credit_ledger (created_at);
-- 同一笔订单只到账一次、只扣回一次（支付通知重复推送、和主动查询同时到达时）
CREATE UNIQUE INDEX uk_credit_order ON t_credit_ledger (kind, ref) WHERE kind IN ('PURCHASE', 'REFUND');

