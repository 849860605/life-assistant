-- 会员账单：每次会员时间变动记一条（付费开通、后台赠送或扣减），用户和后台都能看到来龙去脉
CREATE TABLE t_membership_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES t_user (id) ON DELETE CASCADE,
    days           INT          NOT NULL,              -- 加了多少天，扣减是负数
    source         VARCHAR(16)  NOT NULL,              -- PAY 付费开通 / ADMIN 后台调整
    out_trade_no   VARCHAR(64),                        -- 付费开通对应的订单号
    admin_id       BIGINT,                             -- 后台调整的管理员
    note           VARCHAR(200),
    expires_before TIMESTAMPTZ,                        -- 变动前的到期时间，从没开通过为空
    expires_after  TIMESTAMPTZ  NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_membership_log_user ON t_membership_log (user_id, id DESC);

