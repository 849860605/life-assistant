-- 出游技能表（S0）

CREATE TABLE t_trip (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES t_user (id),
    space_id    BIGINT       NOT NULL DEFAULT 0,
    title       VARCHAR(128) NOT NULL,
    trip_type   VARCHAR(16)  NOT NULL DEFAULT 'CITY',   -- CITY / HIKING / MIXED
    destination VARCHAR(64),
    start_date  DATE,
    end_date    DATE,
    current_ver INT          NOT NULL DEFAULT 0,
    status      VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',  -- DRAFT / CONFIRMED / FINISHED
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_trip_user ON t_trip (user_id, start_date DESC);

-- 每次修改一个版本，可回滚、可对比
CREATE TABLE t_trip_version (
    trip_id     BIGINT       NOT NULL REFERENCES t_trip (id) ON DELETE CASCADE,
    version     INT          NOT NULL,
    content     TEXT         NOT NULL,                  -- 行程正文（Markdown）
    itinerary   JSONB,                                  -- 结构化行程（逐日安排），可选
    change_note VARCHAR(256),
    created_by  VARCHAR(16)  NOT NULL,                  -- USER / AI
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (trip_id, version)
);

CREATE TABLE t_trip_share (
    token      VARCHAR(32) PRIMARY KEY,
    trip_id    BIGINT      NOT NULL REFERENCES t_trip (id) ON DELETE CASCADE,
    permission VARCHAR(16) NOT NULL DEFAULT 'VIEW',
    expire_at  TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
